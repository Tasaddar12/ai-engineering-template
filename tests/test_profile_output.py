class ProfileCase(unittest.TestCase):
    ENV_CLEAR = ("GSD_RUNTIME", "CLAUDE_CONFIG_DIR", "CODEX_HOME", "CLINE_CONFIG_DIR", "GROK_AGENTS_HOME",
                 "XDG_CONFIG_HOME", "OPENCODE_CONFIG_DIR", "KILO_CONFIG_DIR")

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.cleanup_directory)
        self.tmp = os.path.realpath(self.temporary.name)
        self.home = os.path.join(self.tmp, "home")
        os.makedirs(self.home)
        self.project = os.path.join(self.tmp, "project")
        os.makedirs(os.path.join(self.project, ".planning"))
        patcher = mock.patch.dict(os.environ, {"HOME": self.home, "USERPROFILE": self.home})
        patcher.start()
        self.addCleanup(patcher.stop)
        for key in self.ENV_CLEAR:
            os.environ.pop(key, None)
        marker = mock.patch.object(po, "_install_marker_cache", None)
        marker.start()
        self.addCleanup(marker.stop)
        self.templates = os.path.join(self.tmp, "templates")
        os.makedirs(self.templates)
        for name, text in (("user-profile.md", USER_PROFILE_TEMPLATE), ("dev-preferences.md", DEV_PREFERENCES_TEMPLATE)):
            Path(self.templates, name).write_text(text, encoding="utf-8")
        templates = mock.patch.object(po, "TEMPLATES_DIR", Path(self.templates))
        templates.start()
        self.addCleanup(templates.stop)

    def cleanup_directory(self):
        shutil.rmtree(self.tmp, ignore_errors=True)
        self.temporary.cleanup()

    def put(self, relative, content, base=None):
        target = Path(base or self.project, relative)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="")
        return str(target)

    def read(self, path):
        return Path(path).read_bytes().decode("utf-8")

    def call(self, function, *args):
        """Run a command; return (stdout text, stderr text, exit code or None)."""
        out, err = io.StringIO(), io.StringIO()
        code = None
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                function(*args)
            except po.ExitError as exc:
                code = exc.exit_code
        return out.getvalue(), err.getvalue(), code

    def result(self, function, *args):
        out, err, code = self.call(function, *args)
        self.assertIsNone(code, err)
        return json.loads(out)

    def analysis(self, **dimensions):
        data = {"profile_version": "1.0", "dimensions": dimensions or {"communication_style": {"rating": "terse-direct", "confidence": "HIGH"}}}
        return data

    def analysis_file(self, data=None):
        return self.put("analysis.json", json.dumps(data or self.analysis()))


class ProfilingQuestions(unittest.TestCase):
    def test_questions_are_well_formed(self):
        self.assertEqual(8, len(po.PROFILING_QUESTIONS))
        for question in po.PROFILING_QUESTIONS:
            for key in ("dimension", "header", "question", "context"):
                self.assertTrue(question[key], key)
            self.assertGreaterEqual(len(question["options"]), 2)
            for option in question["options"]:
                self.assertTrue(option["label"] and option["value"] and option["rating"])
        dimensions = [question["dimension"] for question in po.PROFILING_QUESTIONS]
        self.assertEqual(len(dimensions), len(set(dimensions)))
        self.assertEqual(DIMENSIONS, dimensions)

    def test_every_dimension_has_instructions_for_every_rating(self):
        self.assertEqual(set(DIMENSIONS), set(po.CLAUDE_INSTRUCTIONS))
        for question in po.PROFILING_QUESTIONS:
            instructions = po.CLAUDE_INSTRUCTIONS[question["dimension"]]
            self.assertTrue(instructions)
            for option in question["options"]:
                self.assertIn(option["rating"], instructions, question["dimension"])

    def test_escaped_quotes_survive_the_port(self):
        first = po.PROFILING_QUESTIONS[0]["options"][0]["label"]
        self.assertEqual('Minimal -- "fix the bug", "add dark mode", just say what\'s needed', first)
        self.assertIn("developer's direct style", po.CLAUDE_INSTRUCTIONS["communication_style"]["terse-direct"])


