        text = self.read(payload["profile_path"])
        self.assertIn("11 pattern(s) redacted", text)
        for secret in ("hunter2", "bob", "alice", "xoxb-123", "t0k"):
            self.assertNotIn(secret, text)
        self.assertIn("[REDACTED]", text)

