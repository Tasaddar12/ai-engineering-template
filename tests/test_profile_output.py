    def test_scoped_write_keeps_untouched_regions_byte_identical(self):
        prior = "# T\nunspaced\n## Old\nbody\n"
        new = "# T\nunspaced\n## Old\nbody\n- item\nnext\n"
        scoped = po._normalize_md(new, prior)
        self.assertTrue(scoped.startswith("# T\nunspaced\n## Old\nbody\n"))
        self.assertEqual("# T\n\nunspaced\n\n## Old\n\nbody\n- item\n\nnext\n", po._normalize_md(new))

