    def test_match_lines(self):
        self.assertEqual([0, 1, 2], po._match_lines(["a", "b", "c"], ["a", "b", "c"]))
        self.assertEqual([0, -1, 2], po._match_lines(["a", "b", "c"], ["a", "x", "c"]))
        self.assertEqual([0, -1, 1], po._match_lines(["a", "c"], ["a", "x", "c"]))
        self.assertEqual([0, 2], po._match_lines(["a", "x", "c"], ["a", "c"]))
        self.assertEqual([-1, -1], po._match_lines(["a"], ["b", "c"]))
        self.assertEqual([-1, 0], po._match_lines(["a", "b"], ["z", "a"]))
        big_prev = [str(n) for n in range(1000)]
        big_next = [f"x{n}" for n in range(1000)]
        self.assertIsNone(po._match_lines(big_prev, big_next))

    def test_write_scope_junctions(self):
        match = po._match_lines(["a", "b", "c"], ["a", "x", "c"])
        scope = po._write_scope(match, 3)
        self.assertTrue(scope.junction_kept(0))
        self.assertTrue(scope.junction_kept(1))
        self.assertTrue(scope.line_written(1))
