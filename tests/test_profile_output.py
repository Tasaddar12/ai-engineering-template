    def test_sensitive_evidence_is_redacted(self):
        secrets = ["sk-" + "a"*24, "Bearer abc.def-ghi", "password: hunter2", "secret=xyz", "token: t0k", "api_key = k1",
                   "/Users/bob/code", "/home/alice/code", "ghp_" + "b"*36, "gho_" + "c"*36, "xoxb-123-abc"]
        evidence = [{"signal": "s " + secrets[0], "quote": " ".join(secrets[1:6]), "example": " ".join(secrets[6:]), "project": "p"}]
        analysis = self.analysis(communication_style={"rating": "r", "confidence": "HIGH", "evidence": evidence})
        out, err, code = self.call(po.cmd_write_profile, self.project, {"input": self.analysis_file(analysis), "output": "p.md"}, True)
