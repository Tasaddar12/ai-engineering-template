"""Generate the schema-derived marked regions of the STATE.md template and reference docs.

Port of ``scripts/gen-state-md-docs.cjs`` from gsd-core at pinned commit
d37ff11b47258b560f0cf8f1132b42ecd90e0c79 (MIT, Copyright (c) 2026 Open GSD).

The generator owns only explicitly MARKED regions inside otherwise hand-authored
files and never touches a byte outside a marker pair. Regions are projected from
``STATE_FIELD_SCHEMA`` (``state_md_schema.py``).

Usage (from ``engineer/bin``)::

    python -m lib.gen_state_md_docs                 # print every region to stdout
    python -m lib.gen_state_md_docs --write         # rewrite every region in place
    python -m lib.gen_state_md_docs --check         # exit 1 if any region is stale
    python -m lib.gen_state_md_docs --json          # --check semantics; JSON report
    python -m lib.gen_state_md_docs --write --force # write despite forceable violations
    python -m lib.gen_state_md_docs ... --root <dir> # resolve targets under <dir>

Deviations:
- ``TARGETS`` lists only ``engineer/templates/state.md`` (region ``frontmatter``).
  Upstream also targets five ``docs/**/reference/state-md.md`` pages; this repo
  has none, so they are exposed as ``DOC_TARGETS`` / ``ALL_TARGETS`` and are
  reachable through ``build_corpus(root, targets=...)`` and
  ``main(argv, targets=...)`` but are not part of the default run.
- Generated markers name the Python helper/schema; old exact markers are accepted
  when regenerating. Frontmatter uses the established ``workflow_state_version``.
- ``ExitError`` / ``runMain`` (``scripts/lib/cli-exit.cjs``) are inlined as a
  private ``_ExitError`` handled by ``main``: a message is written to stderr when
  the code is non-zero, and the code becomes the return value.
- ``--write`` hint text names this module instead of ``node scripts/...``.
- ``schema_lib_missing`` is kept in ``REASON`` but is never emitted: the schema
  is a plain Python import, not a build artifact.
- Target ``relPath`` values use forward slashes on every platform.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from types import MappingProxyType

from .state_md_schema import STATE_FIELD_SCHEMA

REPO_ROOT = Path(__file__).resolve().parents[3]

MARKER_TAG = "STATE-MD-SCHEMA"

REASON = MappingProxyType({
    "SCHEMA_LIB_MISSING": "schema_lib_missing",
    "LOCALE_STRINGS_MISSING": "locale_strings_missing",
    "MARKERS_MISSING": "markers_missing",
    "MARKER_UNCLOSED": "marker_unclosed",
    "MARKER_ORDER_INVALID": "marker_order_invalid",
    "REGION_STALE": "region_stale",
    "FIELD_REFERENCE_DRIFT": "field_reference_drift",
    "STATUS_VALUES_DRIFT": "status_values_drift",
})

_TEMPLATE_TARGET = {"key": "template", "relPath": "engineer/templates/state.md", "regions": ("frontmatter",)}
TARGETS = (_TEMPLATE_TARGET,)
DOC_TARGETS = tuple(
    {"key": locale, "relPath": ("docs/reference/state-md.md" if locale == "en" else f"docs/{locale}/reference/state-md.md"),
     "locale": locale, "regions": ("status-lifecycle", "cardinality")}
    for locale in ("en", "ja-JP", "zh-CN", "ko-KR", "pt-BR"))
ALL_TARGETS = TARGETS + DOC_TARGETS


class _ExitError(Exception):
    def __init__(self, code=1, message=None):
        super().__init__(message if message is not None else f"process exit {code}")
        self.code = code
        self.has_user_message = message is not None


def start_marker(region):
    return f"<!-- {MARKER_TAG}:START:{region} — generated by engineer/bin/helper.py gen-state-md-docs from engineer/bin/lib/state_md_schema.py; do not edit by hand -->"


def end_marker(region):
    return f"<!-- {MARKER_TAG}:END:{region} -->"


# --- Frontmatter region (engineer/templates/state.md) ------------------------

TEMPLATE_FRONTMATTER_FIELDS = ("workflow_state_version", "status", "progress")


def render_frontmatter_region(schema):
    for field in TEMPLATE_FRONTMATTER_FIELDS:
        if field not in schema:
            raise _ExitError(
                1,
                f"template frontmatter field '{field}' is not declared in STATE_FIELD_SCHEMA (src/state-md-schema.cts) "
                "— update TEMPLATE_FRONTMATTER_FIELDS or the schema")
    # Deliberately opens the SAME ```markdown fence the hand-authored File Template
    # body continues in; the END marker lands inside the still-open fence.
    return "\n".join([
        "```markdown",
        "---",
        "workflow_state_version: '1.0'  # placeholder; syncStateFrontmatter overwrites on first state.* call",
        "status: planning",
        "progress:",
        "  total_phases: 0",
        "  completed_phases: 0",
        "  total_plans: 0",
        "  completed_plans: 0",
        "  percent: 0",
        "---",
    ])


# --- Status-lifecycle region (the reference docs) ---------------------------

STATUS_LIFECYCLE_STRINGS = MappingProxyType({
    "en": {"heading": "Status lifecycle (ADR-2207)", "cols": ("Value", "Written by", "Meaning")},
    "ja-JP": {"heading": "ステータスライフサイクル (ADR-2207)", "cols": ("値", "書き込み元", "意味")},
    "zh-CN": {"heading": "状态生命周期 (ADR-2207)", "cols": ("值", "写入方", "含义")},
    "ko-KR": {"heading": "상태 라이프사이클 (ADR-2207)", "cols": ("값", "작성자", "의미")},
    "pt-BR": {"heading": "Ciclo de vida do status (ADR-2207)", "cols": ("Valor", "Escrito por", "Significado")},
})

STATUS_LIFECYCLE_ROWS = (
    ("`Ready to plan`", "`completePhaseCore` (non-last phase)", "Next phase is ready for planning"),
    ("`All phases complete`", "`completePhaseCore` (last phase)", "All phases done; milestone awaiting formal close"),
    ("`<version> milestone complete`", "`milestoneCompleteCore`", "Milestone formally closed and archived"),
    ("`Awaiting next milestone`", "`milestoneCompleteCore`", "Terminal/archived state"),
)

STATUS_LIFECYCLE_INTRO = "The `Status` field follows a strict lifecycle across phase and milestone boundaries:"
STATUS_LIFECYCLE_FOOTNOTE = (
    "Phase-completion verbs never write `Milestone complete` (the overloaded bare value was removed in "
    "#2204 per ADR-2207 to decouple phase-level writes from milestone termination).")


def render_status_lifecycle_region(locale, schema, violations):
    status_row = schema.get("status") if hasattr(schema, "get") else None
    enum = status_row.get("enum") if status_row else None
    if not isinstance(enum, (list, tuple)) or len(enum) == 0:
        raise _ExitError(
            1, "STATE_FIELD_SCHEMA.status must declare a non-empty 'enum' for the status-lifecycle section to be generated")
    strings = STATUS_LIFECYCLE_STRINGS.get(locale)
    if not strings:
        violations.append({"reason": REASON["LOCALE_STRINGS_MISSING"], "file": None, "region": "status-lifecycle", "locale": locale})
        strings = STATUS_LIFECYCLE_STRINGS["en"]
    c0, c1, c2 = strings["cols"]
    lines = [f"### {strings['heading']}", "", STATUS_LIFECYCLE_INTRO, "", f"| {c0} | {c1} | {c2} |", "|---|---|---|"]
    for value, written_by, meaning in STATUS_LIFECYCLE_ROWS:
        lines.append(f"| {value} | {written_by} | {meaning} |")
    lines += ["", STATUS_LIFECYCLE_FOOTNOTE]
    return "\n".join(lines)


# --- Cardinality region (the reference docs) --------------------------------

EXCLUDED_FIELD_TABLE_KEYS = ("progress",)

CARDINALITY_STRINGS = MappingProxyType({
    "en": {"heading": "Field cardinality", "cols": ("Field", "Cardinality")},
    "ja-JP": {"heading": "フィールドの多重度", "cols": ("フィールド", "多重度")},
    "zh-CN": {"heading": "字段基数", "cols": ("字段", "基数")},
    "ko-KR": {"heading": "필드 카디널리티", "cols": ("필드", "카디널리티")},
    "pt-BR": {"heading": "Cardinalidade dos campos", "cols": ("Campo", "Cardinalidade")},
})


def render_cardinality_region(locale, schema):
    strings = CARDINALITY_STRINGS.get(locale)
    if not strings:
        raise _ExitError(1, f"no localized strings registered in CARDINALITY_STRINGS for locale '{locale}'")
    c0, c1 = strings["cols"]
    lines = [f"### {strings['heading']}", "", f"| {c0} | {c1} |", "|---|---|"]
    for key in schema:
        if key in EXCLUDED_FIELD_TABLE_KEYS:
            continue
        lines.append(f"| `{key}` | {schema[key]['cardinality']} |")
    return "\n".join(lines)


# --- Field-reference / status-values key-set parity (detection only) --------

KNOWN_SCHEMA_GAP_FIELDS = ("active_phase", "next_action", "next_phases")

FIELD_REFERENCE_HEADING = MappingProxyType({
    "en": "Field reference", "ja-JP": "フィールドリファレンス", "zh-CN": "字段参考",
    "ko-KR": "필드 참조", "pt-BR": "Referência de campos",
})
STATUS_VALUES_HEADING = MappingProxyType({
    "en": "Status values", "ja-JP": "ステータス値", "zh-CN": "状态值",
    "ko-KR": "상태 값", "pt-BR": "Valores de status",
})

_SEPARATOR_CELL = re.compile(r"^:?-+:?$")


def first_column_after_heading(normalized_text, heading_text):
    """First-column cells of the first markdown table after ``### <heading_text>``, or None."""
    lines = normalized_text.split("\n")
    try:
        heading_idx = lines.index(f"### {heading_text}")
    except ValueError:
        return None
    values = []
    saw_header_row = False
    for line in lines[heading_idx + 1:]:
        if not line.startswith("|"):
            if saw_header_row:
                break
            continue
        cells = line.split("|")
        first = (cells[1] if len(cells) > 1 else "").strip()
        if _SEPARATOR_CELL.match(first):
            continue
        if not saw_header_row:
            saw_header_row = True
            continue
        values.append(first.replace("`", ""))
    return values


def collect_key_set_parity_violations(target, schema, normalized_text):
    locale = target.get("locale")
    if not locale:
        return []
    found = []
    field_heading = FIELD_REFERENCE_HEADING.get(locale)
    doc_field_keys = first_column_after_heading(normalized_text, field_heading) if field_heading else None
    if doc_field_keys is not None:
        schema_keys = [k for k in schema if k not in EXCLUDED_FIELD_TABLE_KEYS]
        doc_set, schema_set = set(doc_field_keys), set(schema_keys)
        missing = [k for k in schema_keys if k not in doc_set]
        undeclared = [k for k in doc_field_keys if k not in schema_set and k not in KNOWN_SCHEMA_GAP_FIELDS]
        if missing or undeclared:
            found.append({"reason": REASON["FIELD_REFERENCE_DRIFT"], "file": target["relPath"], "region": None,
                          "missingFromDoc": missing, "undeclaredInSchema": undeclared})
    status_heading = STATUS_VALUES_HEADING.get(locale)
    doc_status = first_column_after_heading(normalized_text, status_heading) if status_heading else None
    if doc_status is not None:
        status_row = schema.get("status")
        enum_members = list(status_row["enum"]) if status_row and isinstance(status_row.get("enum"), (list, tuple)) else []
        doc_set, enum_set = set(doc_status), set(enum_members)
        missing = [v for v in enum_members if v not in doc_set]
        undeclared = [v for v in doc_status if v not in enum_set]
        if missing or undeclared:
            found.append({"reason": REASON["STATUS_VALUES_DRIFT"], "file": target["relPath"], "region": None,
                          "missingFromDoc": missing, "undeclaredInSchema": undeclared})
    return found


def _render_region(region, target, schema, violations):
    if region == "frontmatter":
        return render_frontmatter_region(schema)
    if region == "status-lifecycle":
        return render_status_lifecycle_region(target.get("locale"), schema, violations)
    if region == "cardinality":
        return render_cardinality_region(target.get("locale"), schema)
    raise _ExitError(1, f"no renderer registered for region '{region}'")


# --- Marker splicing --------------------------------------------------------

def find_region(doc, file, region):
    """Locate a region's [start, end) range inclusive of both marker lines.

    Returns ``{"violation": ...}`` or ``{"range": [start, end]}``. The END marker is found
    with ``rfind`` so a forged marker cannot shrink the region it governs.
    """
    start, end = start_marker(region), end_marker(region)
    legacy_start = f"<!-- {MARKER_TAG}:START:{region} — generated by scripts/gen-state-md-docs.cjs from src/state-md-schema.cts; do not edit by hand -->"
    if start not in doc and legacy_start in doc:
        start = legacy_start
    interim_start = f"<!-- {MARKER_TAG}:START:{region} — generated from the Python state schema; do not edit by hand -->"
    if start not in doc and interim_start in doc:
        start = interim_start
    start_idx, end_idx = doc.find(start), doc.rfind(end)
    if start_idx == -1 and end_idx == -1:
        return {"violation": {"reason": REASON["MARKERS_MISSING"], "file": file, "region": region}}
    if start_idx == -1 or end_idx == -1:
        return {"violation": {"reason": REASON["MARKER_UNCLOSED"], "file": file, "region": region}}
    if end_idx < start_idx:
        return {"violation": {"reason": REASON["MARKER_ORDER_INVALID"], "file": file, "region": region}}
    return {"range": [start_idx, end_idx + len(end)]}


def splice_region(doc, region, body):
    found = find_region(doc, "<in-memory>", region)
    if "violation" in found:
        raise _ExitError(
            1, f"region '{region}' markers are {found['violation']['reason']} — expected:\n  {start_marker(region)}\n  {end_marker(region)}\n")
    start, end = found["range"]
    return doc[:start] + f"{start_marker(region)}\n{body}\n{end_marker(region)}" + doc[end:]


def is_crlf(text):
    return "\r\n" in text


# --- Corpus assembly --------------------------------------------------------

def load_schema():
    return STATE_FIELD_SCHEMA


def build_corpus(files_root, targets=None):
    schema = load_schema()
    violations = []
    built = []
    for target in (TARGETS if targets is None else targets):
        region_bodies = {region: _render_region(region, target, schema, violations) for region in target["regions"]}
        built.append({**target, "absPath": Path(files_root) / target["relPath"], "regionBodies": region_bodies})
    return {"schema": schema, "targets": built, "violations": violations}


def _read_target(target, violations):
    try:
        with open(target["absPath"], "r", encoding="utf-8", newline="") as handle:
            return handle.read()
    except (OSError, UnicodeDecodeError):
        violations.append({"reason": REASON["MARKERS_MISSING"], "file": target["relPath"], "region": None, "detail": "file unreadable"})
        return None


def splice_target(target, original):
    crlf = is_crlf(original)
    normalized = original.replace("\r\n", "\n")
    for region in target["regions"]:
        normalized = splice_region(normalized, region, target["regionBodies"][region])
    return normalized.replace("\n", "\r\n") if crlf else normalized


def stale_regions_of(target, original):
    crlf = is_crlf(original)
    normalized = original.replace("\r\n", "\n")
    stale = []
    for region in target["regions"]:
        found = find_region(normalized, target["relPath"], region)
        if "violation" in found:
            continue
        start, end = found["range"]
        fresh = f"{start_marker(region)}\n{target['regionBodies'][region]}\n{end_marker(region)}"
        if normalized[start:end] != fresh:
            stale.append(region)
    return {"stale": stale, "crlf": crlf}


def collect_target_violations(target, original):
    if original is None:
        return []
    normalized = original.replace("\r\n", "\n")
    found = []
    for region in target["regions"]:
        result = find_region(normalized, target["relPath"], region)
        if "violation" in result:
            found.append({**result["violation"], "file": target["relPath"]})
    return found


def describe_violation(v):
    reason = v["reason"]
    if reason == REASON["SCHEMA_LIB_MISSING"]:
        return "state_md_schema is missing"
    if reason == REASON["MARKERS_MISSING"]:
        return f"{v['file']}: region '{v['region']}' markers are entirely absent — expected {start_marker(v['region'])} / {end_marker(v['region'])}"
    if reason == REASON["MARKER_UNCLOSED"]:
        return f"{v['file']}: region '{v['region']}' has only one of its START/END markers — malformed or unclosed"
    if reason == REASON["MARKER_ORDER_INVALID"]:
        return f"{v['file']}: region '{v['region']}' END marker precedes its START marker"
    if reason == REASON["REGION_STALE"]:
        return f"{v['file']}: region '{v['region']}' is stale — run 'python -m lib.gen_state_md_docs --write'"
    if reason == REASON["LOCALE_STRINGS_MISSING"]:
        return f"no localized strings registered in STATUS_LIFECYCLE_STRINGS for locale '{v['locale']}' — falls back to 'en' under --force"
    if reason == REASON["FIELD_REFERENCE_DRIFT"]:
        return (f"{v['file']}: Field-reference table row set disagrees with STATE_FIELD_SCHEMA — "
                f"missing from doc: [{', '.join(v['missingFromDoc'])}]; undeclared in schema: [{', '.join(v['undeclaredInSchema'])}]")
    if reason == REASON["STATUS_VALUES_DRIFT"]:
        return (f"{v['file']}: Status-values table row set disagrees with STATE_FIELD_SCHEMA.status.enum — "
                f"missing from doc: [{', '.join(v['missingFromDoc'])}]; undeclared in schema: [{', '.join(v['undeclaredInSchema'])}]")
    return f"{v['file']}: {reason}"


# --- CLI ---------------------------------------------------------------------

def parse_args(argv):
    opts = {"write": False, "check": False, "json": False, "force": False, "root": REPO_ROOT}
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg in ("--write", "--check", "--json", "--force"):
            opts[arg[2:]] = True
        elif arg == "--root":
            i += 1
            if i >= len(argv) or not argv[i]:
                raise _ExitError(1, "--root requires a directory argument")
            opts["root"] = argv[i]
        else:
            raise _ExitError(1, f"unknown flag: {arg}\nRecognized flags: --write, --check, --json, --force, --root <dir>.")
        i += 1
    return opts


def _err(text):
    sys.stderr.write(text)


def _run(argv, targets):
    opts = parse_args(argv)
    corpus = build_corpus(opts["root"], targets)
    schema, built, violations = corpus["schema"], corpus["targets"], corpus["violations"]

    originals = {}
    for target in built:
        original = _read_target(target, violations)
        originals[target["key"]] = original
        violations.extend(collect_target_violations(target, original))
        if original is not None:
            violations.extend(collect_key_set_parity_violations(target, schema, original.replace("\r\n", "\n")))

    hostile_reasons = (REASON["MARKERS_MISSING"], REASON["MARKER_UNCLOSED"], REASON["MARKER_ORDER_INVALID"])
    hostile = [v for v in violations if v["reason"] in hostile_reasons]

    stale_targets = []
    for target in built:
        original = originals[target["key"]]
        if original is None or any(v["file"] == target["relPath"] for v in hostile):
            continue
        stale = stale_regions_of(target, original)["stale"]
        if stale:
            stale_targets.append(target)
            for region in stale:
                violations.append({"reason": REASON["REGION_STALE"], "file": target["relPath"], "region": region})

    if opts["json"]:
        ok = len(violations) == 0
        sys.stdout.write(json.dumps({"ok": ok, "targetCount": len(built), "staleCount": len(stale_targets), "violations": violations},
                                    separators=(",", ":"), ensure_ascii=False) + "\n")
        return 0 if ok else 1

    if opts["check"]:
        if violations:
            _err(f"gen-state-md-docs: {len(violations)} violation(s).\n\n")
            for v in violations:
                _err(f"  ✗ {describe_violation(v)}\n")
            _err("\n")
            raise _ExitError(1)
        sys.stdout.write(f"All {len(built)} target(s) are up to date.\n")
        return 0

    if opts["write"]:
        if hostile:
            _err(f"gen-state-md-docs: refusing to write — {len(hostile)} target(s) have broken markers.\n\n")
            for v in hostile:
                _err(f"  ✗ {describe_violation(v)}\n")
            _err("\n")
            raise _ExitError(1)
        others = [v for v in violations if v["reason"] != REASON["REGION_STALE"] and v not in hostile]
        if others and not opts["force"]:
            _err(f"gen-state-md-docs: {len(others)} violation(s). Refusing to write; pass --force to override.\n\n")
            for v in others:
                _err(f"  ✗ {describe_violation(v)}\n")
            _err("\n")
            raise _ExitError(1)
        written = 0
        for target in built:
            original = originals[target["key"]]
            if original is None or any(v["file"] == target["relPath"] for v in hostile):
                continue
            spliced = splice_target(target, original)
            if spliced != original:
                with open(target["absPath"], "w", encoding="utf-8", newline="") as handle:
                    handle.write(spliced)
                written += 1
        sys.stdout.write(f"Wrote {written} of {len(built)} target(s).\n")
        return 0

    for target in built:
        for region in target["regions"]:
            sys.stdout.write(f"\n=== {target['relPath']} :: {region} ===\n")
            sys.stdout.write(target["regionBodies"][region] + "\n")
    return 0


def main(argv=None, targets=None):
    """CLI entry point. ``targets`` defaults to ``TARGETS``; returns the process exit code."""
    try:
        return _run(list(sys.argv[1:] if argv is None else argv), TARGETS if targets is None else targets)
    except _ExitError as exc:
        if exc.has_user_message and exc.code != 0:
            sys.stderr.write(f"{exc}\n")
        return exc.code


if __name__ == "__main__":
    for _stream in (sys.stdout, sys.stderr):
        try:
            _stream.reconfigure(encoding="utf-8")
        except (AttributeError, ValueError):
            pass
    raise SystemExit(main())
