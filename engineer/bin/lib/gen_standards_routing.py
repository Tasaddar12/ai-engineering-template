"""Generate the routing-table regions of the standards indexes from ``routing.json``.

``engineer/standards/routing.json`` is the routing source of truth. The generator
owns only the marked regions inside each ``engineer/standards/<domain>/index.md``
and never touches a byte outside a marker pair; index prose stays hand-authored.

Usage (from ``engineer/bin``)::

    python -I engineer/bin/lib/gen_standards_routing.py            # print every rendered region
    python -I engineer/bin/lib/gen_standards_routing.py --write    # rewrite stale regions in place
    python -I engineer/bin/lib/gen_standards_routing.py --check    # exit 1 if any region is stale or missing
    python -I engineer/bin/lib/gen_standards_routing.py ... --root <dir>

``--check`` also exits 1 when routing.json is invalid or an index carries a
START marker for a region routing.json does not define.
"""
COMMAND = "python -I engineer/bin/lib/gen_standards_routing.py"
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from lib import standards  # noqa: E402
else:
    from . import standards

MARKER_TAG = "STANDARDS-ROUTING"
HEADER = "| ID suffix / concern | Reference and section selectors |\n|---|---|"


def start_marker(region):
    return (f"<!-- {MARKER_TAG}:START:{region} — generated by engineer/bin/lib/gen_standards_routing.py "
            "from engineer/standards/routing.json; do not edit by hand -->")


def end_marker(region):
    return f"<!-- {MARKER_TAG}:END:{region} -->"


def render_group(domain, group, prefix_lines):
    lines = [*prefix_lines, *([""] if prefix_lines else []), HEADER]
    for entry in group["entries"]:
        suffix = entry["id"][len(domain["domain"]) + 1:]
        lines.append(f"| `{suffix}` — {entry['concern']} | `{entry['path']}`{entry['menu']} |")
    return "\n".join(lines)


def render_domain(domain):
    """Return ``{region: text}`` for one domain; each prefix include renders above its first matching group."""
    pending = list(domain.get("prefix_includes", []))
    regions = {}
    for group in domain["groups"]:
        suffixes = [entry["id"][len(domain["domain"]) + 1:] for entry in group["entries"]]
        here = [p for p in pending if any(s.startswith(p["prefix"] + ".") for s in suffixes)]
        pending = [p for p in pending if p not in here]
        prefix_lines = [f"Every `{p['prefix']}.*` row includes `{p['path']}` §{p['section']}." for p in here]
        regions[group["region"]] = render_group(domain, group, prefix_lines)
    return regions


def _replace(text, region, body, path):
    start, end = start_marker(region), end_marker(region)
    head, sep, rest = text.partition(start)
    if not sep:
        raise standards.Failure("standards-routing-markers-missing", f"{path}: no START marker for region {region}", 1)
    old, sep, tail = rest.partition(end)
    if not sep:
        raise standards.Failure("standards-routing-markers-missing", f"{path}: no END marker for region {region}", 1)
    return head + start + "\n" + body + "\n" + end + tail, old != "\n" + body + "\n"


def build(root):
    """Return ``[(path, new_text, stale_regions)]`` for every index named in routing.json."""
    data = standards.load_routing(root)
    findings = standards.validate_routing(data, root)
    if findings:
        raise standards.Failure("standards-routing-invalid", "; ".join(findings), 1)
    results = []
    for domain in data["domains"]:
        path = root/domain["index"]
        text = path.read_text(encoding="utf-8")
        regions = render_domain(domain)
        marked = re.findall(rf"<!-- {MARKER_TAG}:START:([\w-]+) ", text)
        unknown = sorted(set(marked) - set(regions))
        repeated = sorted({region for region in marked if marked.count(region) > 1})
        if unknown or repeated:
            raise standards.Failure("standards-routing-markers-invalid",
                                    f"{domain['index']}: unknown regions {unknown}, repeated regions {repeated}", 1)
        stale = []
        for region, body in regions.items():
            text, changed = _replace(text, region, body, domain["index"])
            if changed:
                stale.append(region)
        results.append((path, text, stale, regions))
    return results


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    argv = list(sys.argv[1:] if argv is None else argv)
    root, flags = Path(__file__).resolve().parents[3], set()
    usage = "Recognized flags: --write, --check, --root <dir>."
    position = 0
    while position < len(argv):
        arg = argv[position]
        if arg == "--root":
            if position + 1 >= len(argv) or argv[position + 1].startswith("--"):
                print(f"--root requires a directory argument\n{usage}", file=sys.stderr)
                return 2
            root, position = Path(argv[position + 1]), position + 2
            continue
        if arg not in ("--write", "--check"):
            print(f"unknown flag: {arg}\n{usage}", file=sys.stderr)
            return 2
        flags.add(arg)
        position += 1
    if flags == {"--write", "--check"}:
        print(f"--write and --check are mutually exclusive\n{usage}", file=sys.stderr)
        return 2
    try:
        results = build(root)
    except standards.Failure as exc:
        print(exc.message, file=sys.stderr)
        return 1
    if "--write" in flags:
        for path, text, stale, _ in results:
            if stale:
                path.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if "--check" in flags:
        stale = [f"{path.relative_to(root).as_posix()}: region '{region}' is stale — run '{COMMAND} --write'"
                 for path, _, regions, _ in results for region in regions]
        for line in stale:
            print(line, file=sys.stderr)
        return 1 if stale else 0
    for path, _, _, regions in results:
        for region, body in regions.items():
            print(f"{start_marker(region)}\n{body}\n{end_marker(region)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
